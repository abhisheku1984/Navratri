#!/usr/bin/env node
/**
 * Seed a PostgreSQL database from src/content.
 *
 *   node db/seed.mjs --dry-run > seed.sql     # emit SQL, touch nothing
 *   node db/seed.mjs                          # apply to DATABASE_URL
 *
 * This script is intentionally dependency-free. It reads the same normalised
 * JSON the app reads, and emits INSERTs in an order that satisfies the foreign
 * keys. Run db/schema.sql first.
 *
 * It writes no secrets and requires no credentials unless you apply it.
 */
import { readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "src", "content");

const readJson = (...parts) => JSON.parse(readFileSync(join(CONTENT, ...parts), "utf8"));

/* ------------------------------------------------------------------ quoting */

/** Single-quote escaping per the SQL standard; backslashes are not special. */
const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  return `'${String(v).replace(/'/g, "''")}'`;
};

/** NULL for empty strings, so a missing field is never an empty claim. */
const t = (v) => (v === null || v === undefined || v === "" ? "NULL" : q(v));

const insert = (table, cols, rows) => {
  if (!rows.length) return "";
  return (
    `INSERT INTO ${table} (${cols.join(", ")}) VALUES\n` +
    rows.map((r) => `  (${r.map((c) => c).join(", ")})`).join(",\n") +
    "\nON CONFLICT DO NOTHING;\n"
  );
};

/* ------------------------------------------------------------------- tables */

const out = [];
out.push("-- Generated by db/seed.mjs from src/content. Do not edit by hand.\n");
out.push("BEGIN;\n");

// -- source -----------------------------------------------------------------
const sources = readJson("sources.json").sources;
out.push(insert("source",
  ["id", "kind", "title", "provenance", "author", "published", "edition_note",
   "local_copy", "digital_copy", "derived_note", "licence", "verification", "status"],
  sources.map((s) => [
    q(s.id), q(s.kind), q(s.title), t(s.provenance), t(s.author), t(s.published),
    t(s.editionNote), t(s.localCopy), t(s.digitalCopy), t(s.derived),
    q(s.licence ?? "unspecified"), t(s.verification), q(s.status),
  ])));

out.push(insert("source_person", ["source_id", "role", "name"],
  sources.flatMap((s) => {
    const p = s.people ?? {};
    return [
      ...(p.transcribers ?? []).map((n) => [q(s.id), q("transcriber"), q(n)]),
      ...(p.proofreaders ?? []).map((n) => [q(s.id), q("proofreader"), q(n)]),
      ...(s.author ? [[q(s.id), q("translator"), q(s.author)]] : []),
    ];
  })));

out.push(insert("source_caveat", ["source_id", "position", "caveat"],
  sources.flatMap((s) => (s.caveats ?? []).map((c, i) => [q(s.id), i, q(c)]))));

// -- scripture --------------------------------------------------------------
const manifest = readJson("scripture", "manifest.json");
const charitraOf = (n) => (n === 1 ? "prathama" : n <= 4 ? "madhyama" : "uttama");

out.push(insert("scripture_chapter",
  ["id", "number", "slug", "charitra", "presiding_deity", "title_sanskrit",
   "title_itrans", "title_iast", "title_english_editorial",
   "markandeya_purana_chapter", "verse_unit_count", "traditional_verse_count",
   "source_id", "verification_status", "status"],
  manifest.chapters.map((e) => {
    const ch = readJson("scripture", "chapters", `${String(e.number).padStart(2, "0")}.json`);
    return [
      q(ch.id), ch.number, q(ch.slug), q(charitraOf(ch.number)), q(ch.presidingDeity),
      q(ch.titleSanskrit), q(ch.titleItrans), q(ch.titleIast), q(ch.titleEnglishEditorial),
      ch.markandeyaPuranaChapter, ch.verseUnitCount, ch.traditionalVerseCount,
      q(manifest.source.id), q("verified"), q("published"),
    ];
  })));

const verseRows = [];
for (const file of readdirSync(join(CONTENT, "scripture", "chapters")).sort()) {
  const ch = readJson("scripture", "chapters", file);
  ch.verses.forEach((v, i) => verseRows.push([
    q(ch.id), v.n, v.nEnd, q(v.label), i, t(v.speaker),
    q(v.iTrans), q(v.devanagari), q(v.iast), v.padas,
  ]));
}
out.push(insert("scripture_verse",
  ["chapter_id", "n", "n_end", "label", "ordinal", "speaker", "itrans",
   "devanagari", "iast", "padas"], verseRows));

const angaRows = [];
const angaVerseRows = [];
for (const file of readdirSync(join(CONTENT, "scripture", "angas")).sort()) {
  const a = readJson("scripture", "angas", file);
  angaRows.push([
    q(a.id), q(a.slug), q(a.titleEnglish), q(a.titleSanskrit), q(a.titleItrans),
    q(a.titleIast), q(a.kind), a.order, t(a.note),
    a.verseUnitCount, a.traditionalVerseCount, q(manifest.source.id), q("verified"),
  ]);
  // Anga verses carry no nEnd: unlike the chapters, an auxiliary verse is never
  // a range. n and padas arrive as strings from the importer, so coerce.
  a.verses.forEach((v, i) => angaVerseRows.push([
    q(a.id), Number(v.n), Number(v.n), q(v.label), i,
    q(v.iTrans), q(v.devanagari), q(v.iast), Number(v.padas),
  ]));
}
out.push(insert("auxiliary_recitation",
  ["id", "slug", "title_english", "title_sanskrit", "title_itrans", "title_iast",
   "kind", "sort_order", "note", "verse_unit_count", "traditional_verse_count",
   "source_id", "verification_status"], angaRows));
out.push(insert("auxiliary_verse",
  ["recitation_id", "n", "n_end", "label", "ordinal", "itrans", "devanagari",
   "iast", "padas"], angaVerseRows));

// -- translations -----------------------------------------------------------
const trManifest = readJson("scripture", "translations", "en-pargiter-1904", "manifest.json");
out.push(insert("translation",
  ["id", "language", "title", "translator", "work", "copyright_status",
   "digital_copy", "ocr_uncorrected", "granularity", "verse_alignment",
   "source_id", "verification_status"],
  [[q(trManifest.translationId), q("en"), q(trManifest.title),
    q("F. Eden Pargiter"), q("The Markandeya Purana, Bibliotheca Indica, 1904"),
    q(trManifest.copyrightStatus), q("Archive.org witness cu31924022991974"),
    trManifest.ocrUncorrected, q(trManifest.granularity),
    "NULL", q("pargiter-1904"), q("partially-verified")]]));

const trChapRows = [];
const trParaRows = [];
const trArgRows = [];
for (let n = 1; n <= 13; n++) {
  const tr = readJson("scripture", "translations", "en-pargiter-1904",
                      `${String(n).padStart(2, "0")}.json`);
  const chId = manifest.chapters.find((c) => c.number === n).id;
  trChapRows.push([q(tr.translationId), q(chId), q(tr.witness.status), tr.wordCount]);
  tr.paragraphs.forEach((p, i) => trParaRows.push([
    q(tr.translationId), q(chId), i, q(p), "NULL", "NULL", "NULL", "NULL",
  ]));
  (tr.argument ?? []).forEach((p, i) => trArgRows.push([q(tr.translationId), q(chId), i, q(p)]));
}
out.push(insert("translation_chapter",
  ["translation_id", "chapter_id", "witness_status", "word_count"], trChapRows));
out.push(insert("translation_paragraph",
  ["translation_id", "chapter_id", "position", "body", "verse_start", "verse_end",
   "reviewer", "reviewed_at"], trParaRows));
out.push(insert("translation_argument",
  ["translation_id", "chapter_id", "position", "body"], trArgRows));

// -- navadurga --------------------------------------------------------------
const forms = readJson("navadurga.json").forms;
out.push(insert("navadurga_form",
  ["id", "slug", "day", "form", "name_devanagari", "name_hindi",
   "name_transliterated", "meaning", "origin_story", "iconography", "colour",
   "colour_note", "chakra", "planet", "scripture_ref", "family_story",
   "regional_variation_note", "sample_content", "source_id", "verification_status"],
  forms.map((f) => [
    q(f.id), q(f.slug), f.day, q(f.slug), q(f.nameDevanagari), q(f.nameHindi),
    q(f.nameTransliterated), q(f.meaning), q(f.originStory), q(f.iconography),
    q(f.colour), t(f.colourNote), t(f.chakra), t(f.planet), t(f.scriptureRef),
    q(f.familyStory), q(f.regionalVariationNote), Boolean(f.sampleContent),
    q("navadurga-stotram"), q("partially-verified"),
  ])));

out.push(insert("navadurga_symbolism", ["form_id", "position", "attribute", "meaning"],
  forms.flatMap((f) => f.symbolism.map((s, i) => [q(f.id), i, q(s.attribute), q(s.meaning)]))));
out.push(insert("navadurga_quality", ["form_id", "position", "quality"],
  forms.flatMap((f) => f.qualities.map((x, i) => [q(f.id), i, q(x)]))));
out.push(insert("navadurga_offering", ["form_id", "flower", "bhog", "note"],
  forms.map((f) => [q(f.id), q(f.offering.flower), q(f.offering.bhog), t(f.offering.note)])));
out.push(insert("navadurga_routine_step", ["form_id", "position", "step", "body"],
  forms.flatMap((f) => f.fiveMinuteRoutine.map((r, i) => [q(f.id), i, q(r.step), q(r.text)]))));

out.push(insert("navadurga_verse",
  ["form_id", "slot", "devanagari", "transliteration", "meaning", "source",
   "source_file", "note", "status"],
  forms.flatMap((f) => [
    [q(f.id), q("dhyana"), t(f.dhyanaVerse.devanagari), "NULL", "NULL",
     t(f.dhyanaVerse.source), t(f.dhyanaVerse.sourceFile), t(f.dhyanaVerse.note),
     q(f.dhyanaVerse.status)],
    [q(f.id), q("kavacham_name"), t(f.kavachamNameVerse.devanagari), "NULL", "NULL",
     t(f.kavachamNameVerse.source), "NULL", "NULL", q("imported")],
    [q(f.id), q("navarna_mantra"), t(f.navarnaMantra.devanagari),
     t(f.navarnaMantra.transliteration), t(f.navarnaMantra.meaning),
     "NULL", "NULL", t(f.navarnaMantra.note), q("imported")],
  ])));

// -- peethas ----------------------------------------------------------------
const peethaCol = readJson("peethas.json");
out.push(insert("peetha_tradition_list", ["slug", "label", "note"],
  Object.entries(peethaCol.lists).map(([slug, v]) =>
    [q(slug), q(v.label ?? slug), q(v.note ?? "")])));

out.push(insert("peetha",
  ["id", "slug", "temple_name", "goddess_name", "bhairava", "city", "region",
   "country", "lat", "lon", "coordinate_note", "tradition_note", "story",
   "confidence", "verification_status", "last_checked", "verification_note",
   "official_website", "darshan_timings", "accessibility", "visitor_info_note",
   "sample_content"],
  peethaCol.peethas.map((p) => [
    q(p.id), q(p.slug), q(p.templeName), q(p.goddessName), t(p.bhairava),
    q(p.location.city), t(p.location.region), q(p.location.country),
    p.coordinates ? p.coordinates.lat : "NULL",
    p.coordinates ? p.coordinates.lon : "NULL",
    t(p.coordinateNote), q(p.traditionNote), q(p.story), q(p.confidence),
    q(p.verificationStatus.status), t(p.verificationStatus.lastChecked),
    t(p.verificationStatus.note),
    // Deliberately NULL. No website or darshan time has been verified, and
    // inventing one would be worse than leaving the column empty.
    "NULL", "NULL", t(p.accessibility), q(p.visitorInfoNote),
    Boolean(p.sampleContent),
  ])));

out.push(insert("peetha_list_membership", ["peetha_id", "list_slug"],
  peethaCol.peethas.flatMap((p) => p.lists.map((l) => [q(p.id), q(l)]))));

// -- temples ----------------------------------------------------------------
const temples = readJson("temples.json").temples;
out.push(insert("temple",
  ["id", "slug", "name", "city", "region", "country", "lat", "lon",
   "coordinate_note", "kind", "note", "peetha_id", "official_website",
   "opening_hours", "contact", "accessibility", "info_status", "info_note",
   "sample_content"],
  temples.map((x) => [
    q(x.id), q(x.slug), q(x.name), q(x.city), t(x.region), q(x.country),
    x.coordinates ? x.coordinates.lat : "NULL",
    x.coordinates ? x.coordinates.lon : "NULL",
    t(x.coordinateNote), q(x.kind), q(x.note),
    x.kind === "shakti-peetha" ? q(x.id) : "NULL",
    "NULL", "NULL", "NULL", t(x.accessibility), q(x.infoStatus), q(x.infoNote),
    Boolean(x.sampleContent),
  ])));
out.push(insert("temple_festival", ["temple_id", "position", "festival"],
  temples.flatMap((x) => (x.festivals ?? []).map((f, i) => [q(x.id), i, q(f)]))));

// -- editorial --------------------------------------------------------------
const topics = readJson("knowledge.json").topics;
out.push(insert("knowledge_topic",
  ["id", "slug", "title", "title_hi", "tagline", "story", "significance",
   "source_note", "child_version", "claim_class", "verification_status", "status"],
  topics.map((x) => [
    q(x.slug), q(x.slug), q(x.title), q(x.titleHi), q(x.tagline), q(x.story),
    q(x.significance), q(x.source), q(x.childVersion), q("mixed"),
    q("awaiting-review"), q("published"),
  ])));
out.push(insert("knowledge_detail", ["topic_id", "position", "heading", "body"],
  topics.flatMap((x) => x.detail.map(([h, b], i) => [q(x.slug), i, q(h), q(b)]))));
out.push(insert("knowledge_character", ["topic_id", "position", "name"],
  topics.flatMap((x) => x.characters.map((c, i) => [q(x.slug), i, q(c)]))));
out.push(insert("knowledge_place", ["topic_id", "position", "name"],
  topics.flatMap((x) => x.places.map((c, i) => [q(x.slug), i, q(c)]))));
out.push(insert("knowledge_reflection", ["topic_id", "position", "question"],
  topics.flatMap((x) => x.reflection.map((c, i) => [q(x.slug), i, q(c)]))));
out.push(insert("knowledge_related", ["topic_id", "related_slug"],
  topics.flatMap((x) => x.related.map((r) => [q(x.slug), q(r)]))));

const mantras = readJson("mantras.json").items;
out.push(insert("mantra",
  ["id", "slug", "title", "deva", "iast", "category", "attribution", "meaning",
   "pronunciation", "text_status", "text_status_note", "chapter_ref",
   "full_text_href", "source_href", "verification_status"],
  mantras.map((m) => [
    q(m.slug), q(m.slug), q(m.title), q(m.deva), t(m.iast), q(m.category),
    q(m.attribution), q(m.meaning), q(m.pronunciation), q(m.textStatus),
    t(m.textStatusNote), t(m.chapterRef), t(m.fullTextRef), t(m.sourceRef),
    q(m.textStatus === "imported" ? "verified" : "awaiting-review"),
  ])));
out.push(insert("mantra_word_meaning", ["mantra_id", "position", "word", "meaning"],
  mantras.flatMap((m) => m.wordMeaning.map(([w, d], i) => [q(m.slug), i, q(w), q(d)]))));

const stories = readJson("stories.json").stories;
out.push(insert("story",
  ["id", "slug", "title", "title_hi", "age_label", "minutes", "short",
   "long_form", "moral", "source_note", "verification_status", "status"],
  stories.map((s) => [
    q(s.slug), q(s.slug), q(s.title), q(s.titleHi), q(s.age), s.minutes,
    q(s.short), q(s.long), q(s.moral), q(s.sourceNote),
    q("awaiting-review"), q("published"),
  ])));
out.push(insert("story_illustration_hint", ["story_id", "position", "hint"],
  stories.flatMap((s) => (s.illustrationHints ?? []).map((h, i) => [q(s.slug), i, q(h)]))));

const guides = readJson("puja.json").guides;
out.push(insert("puja_guide",
  ["id", "slug", "title", "summary", "verification_status", "status"],
  guides.map((g) => [q(g.slug), q(g.slug), q(g.title), q(g.summary),
                     q("awaiting-review"), q("published")])));
out.push(insert("puja_section", ["guide_id", "position", "heading", "body"],
  guides.flatMap((g) => g.sections.map((s, i) => [q(g.slug), i, q(s.heading), q(s.body)]))));

const obs = readJson("festivals.json").observances;
out.push(insert("festival_observance", ["id", "slug", "name", "kind", "months", "summary"],
  obs.map((o) => [q(o.slug), q(o.slug), q(o.name), q(o.kind), q(o.months), q(o.summary)])));
out.push(insert("festival_practice", ["observance_id", "position", "practice"],
  obs.flatMap((o) => (o.practices ?? []).map((p, i) => [q(o.slug), i, q(p)]))));

const terms = readJson("glossary.json").terms;
out.push(insert("glossary_term", ["id", "english", "devanagari", "definition"],
  terms.map((x) => [q(x.id), q(x.english), q(x.devanagari), q(x.definition)])));

const quizzes = readJson("quiz.json").quizzes;
out.push(insert("quiz", ["id", "title", "topic"],
  quizzes.map((x) => [q(x.id), q(x.title), q(x.topic)])));
out.push(insert("quiz_question", ["quiz_id", "position", "question", "answer", "why"],
  quizzes.flatMap((x) => x.questions.map((qq, i) =>
    [q(x.id), i, q(qq.q), qq.answer, q(qq.why)]))));
out.push(insert("quiz_option", ["quiz_id", "position", "opt_pos", "body"],
  quizzes.flatMap((x) => x.questions.flatMap((qq, i) =>
    qq.options.map((o, j) => [q(x.id), i, j, q(o)])))));

const locs = readJson("locations.json").locations;
out.push(insert("location",
  ["id", "city", "region", "country", "lat", "lon", "utc_offset_hours", "timezone"],
  locs.map((l) => [q(l.id), q(l.city), q(l.region), q(l.country),
                   l.lat, l.lon, l.utcOffsetHours, q(l.timezone)])));

out.push("COMMIT;\n");

const sql = out.filter(Boolean).join("\n");

if (process.argv.includes("--dry-run")) {
  process.stdout.write(sql);
} else if (!process.env.DATABASE_URL) {
  console.error(
    "DATABASE_URL is not set.\n" +
    "  node db/seed.mjs --dry-run > seed.sql   # inspect the SQL\n" +
    "  DATABASE_URL=postgres://... node db/seed.mjs\n",
  );
  process.exit(1);
} else {
  // Applying needs a driver. Kept out of the repo on purpose so the seed script
  // has no dependencies; pipe the dry run into psql instead.
  console.error(
    "Apply with psql so no driver dependency is needed:\n" +
    "  node db/seed.mjs --dry-run | psql \"$DATABASE_URL\"\n",
  );
  process.exit(1);
}
